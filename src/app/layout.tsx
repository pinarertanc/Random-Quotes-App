import { Geist, Geist_Mono } from "next/font/google";
import "./globals.css";
import { QuotesContextProvider } from "@/app/context/QuotesContext";
import { ThemeProvider } from "@/app/components/theme-provider";
import { Button} from '@/app/components/ui/button';
import { auth0 } from "@/lib/auth0";
import Link from "next/link";
import { GearIcon } from "@phosphor-icons/react/dist/ssr"
import Image from "next/image";


const geistSans = Geist({
  variable: "--font-geist-sans",
  subsets: ["latin"],
});

const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
});

export const metadata = {
  title: "Create Next App",
  description: "Generated by create next app",
};



export default async function RootLayout({ children }) {
  const session = await auth0.getSession();
  const user = session?.user;

  return (
    <html
      lang="en"
      className={`${geistSans.variable} ${geistMono.variable} h-full antialiased`}
      suppressHydrationWarning
    >
      <body className="min-h-full flex flex-col">
        <nav className="relative shadow-xl h-full max-h-18 ">
          <ul className="flex justify-between w-full items-center max-w-8xl py-2 px-15">
            {session ? (
            <>
            <div className="flex gap-3">
              <li> 
              <Button asChild>
                <Link href="/">Home</Link>
              </Button>
              </li>
              <li> 
              <Button asChild>
                <Link href="/user/quotes/favorite">My Favorite Quotes</Link>
              </Button>
              </li>
              </div>
              <div className="flex items-center gap-3">
                <li>
                  <Image className="rounded-full border-2 border-(--chart-2)/50" src={user?.picture } alt="profile picture" width={50} height={50} loading="eager" />
                </li>
              <li>
              <Button asChild>
                <a href="/auth/logout">LogOut</a>
              </Button>
              </li>
              <li> 
              <Button asChild>
                <Link href="/user/settings"><GearIcon size={32} /></Link>
              </Button>
              </li>
              </div>
            </>  
              ) : ( 
            <li className="flex gap-3">
              <Button asChild>
                 <a href="/auth/login">LogIn</a>
              </Button>
            </li>  
            )}
          </ul>
        </nav>
        <ThemeProvider attribute="class" defaultTheme="system" enableSystem>
      <QuotesContextProvider>{children}</QuotesContextProvider>
      </ThemeProvider>
      </body>
    </html>
  );
}
